def safe(v):
    """Convert a single scalar (possibly a numpy scalar, NaN, or +/-Inf)
    into a plain, JSON-serialisable Python value for embedding in the
    dashboard's JSON payload. NaN/Inf -> None (renders as "n/a"/"—" in the
    dashboard); numpy int/float -> native int/float; everything else is
    passed through unchanged."""
    if v is None:
        return None
    if isinstance(v, (np.floating, float)):
        v = float(v)
        return None if (math.isnan(v) or math.isinf(v)) else v
    if isinstance(v, (np.integer, int)):
        return int(v)
    try:
        if pd.isna(v):
            return None
    except (TypeError, ValueError):
        pass
    return v


