def normalize_header(s):
    s = unicodedata.normalize("NFKC", str(s))
    s = s.replace("\xa0", " ").replace("\u2013", "-").replace("\u2014", "-")
    s = re.sub(r"\s+", " ", s).strip().lower()
    return s


def robust_read_csv(filename):
    """Read a CSV that may contain malformed rows without ever crashing."""
    is_stream = hasattr(filename, "seek")
    if is_stream:
        filename.seek(0)
    try:
        return pd.read_csv(filename), []
    except pd.errors.ParserError:
        pass
    if is_stream:
        filename.seek(0)
    bad_lines = []

    def _capture(bad_line):
        bad_lines.append(",".join(bad_line)[:120])
        return None

    df = pd.read_csv(filename, engine="python", on_bad_lines=_capture)
    return df, bad_lines


def find_column(cols_lower, used, aliases):
    for alias in aliases:
        if alias in cols_lower and cols_lower[alias] not in used:
            return cols_lower[alias]
    for alias in aliases:
        for col_norm, col_orig in cols_lower.items():
            if alias in col_norm and col_orig not in used:
                return col_orig
    return None


def load_and_map(raw):
    cols_lower = {normalize_header(c): c for c in raw.columns}
    mapped, used = {}, set()
    for canon, aliases in COLUMN_ALIASES.items():
        found = find_column(cols_lower, used, aliases)
        if found:
            mapped[canon] = found
            used.add(found)

    required = ["company", "market_cap", "pe", "roe"]
    missing = [k for k in required if k not in mapped]

    out = pd.DataFrame()
    for canon, orig in mapped.items():
        out[canon] = raw[orig]
    return out, mapped, missing


def to_numeric(series):
    cleaned = (series.astype(str)
               .str.replace("\xa0", " ", regex=False)
               .str.replace(r"[₹$,%]", "", regex=True)
               .str.strip())
    cleaned = cleaned.replace({"NM": np.nan, "N/A": np.nan, "NA": np.nan,
                                "-": np.nan, "": np.nan, "nan": np.nan, "None": np.nan})
    out = pd.to_numeric(cleaned, errors="coerce")
    out = out.replace([np.inf, -np.inf], np.nan)
    return out


def to_safe_int(s, default_val=0):
    """Utility to safely convert Series containing NaNs/Infs to int without throwing pandas exceptions"""
    if s is None:
        return default_val
    s_pd = pd.Series(s)
    s_clean = s_pd.replace([np.inf, -np.inf], np.nan).fillna(default_val)
    return s_clean.round().astype(int)


def clean_pipeline(raw):
    """Runs the full clean/normalise pipeline. Never raises. Returns
    (df, log) where log is a list of human-readable data-quality notes."""
    log = []
    df, colmap, missing = load_and_map(raw)
    log.append(f"Mapped {len(colmap)} of {len(COLUMN_ALIASES)} recognised metric columns from your file.")
    if missing:
        log.append(f"WARNING: could not confidently find columns for: {', '.join(missing)}. "
                    f"Scores relying on these will fall back gracefully.")

    if "company" not in df.columns:
        raise ValueError("No company/name column could be identified in the uploaded file.")

    before = len(df)
    df = df[df["company"].astype(str).str.strip().replace({"nan": ""}) != ""].copy()
    blank_dropped = before - len(df)
    if blank_dropped:
        log.append(f"Skipped {blank_dropped} row(s) with a blank company name.")

    for c in NUMERIC_FIELDS:
        if c in df.columns:
            df[c] = to_numeric(df[c])

    before = len(df)
    key = "ticker" if "ticker" in df.columns else "company"
    if "market_cap" in df.columns:
        df = df.sort_values("market_cap", ascending=False, na_position="last")
    df = df.drop_duplicates(subset=[key], keep="first").reset_index(drop=True)
    dup_dropped = before - len(df)
    if dup_dropped:
        log.append(f"Removed {dup_dropped} duplicate company entr{'y' if dup_dropped == 1 else 'ies'} "
                    f"(kept the largest market-cap instance of each).")

    # valuation sanity: a negative multiple isn't "cheap"
    for c in ("pe", "pb", "ev_ebitda"):
        if c in df.columns:
            n_bad = int((df[c] <= 0).sum())
            if n_bad:
                df.loc[df[c] <= 0, c] = np.nan

    if "market_cap" in df.columns and MIN_MARKET_CAP_CR > 0:
        before = len(df)
        df = df[(df["market_cap"] >= MIN_MARKET_CAP_CR) | df["market_cap"].isna()].reset_index(drop=True)
        excl = before - len(df)
        if excl:
            log.append(f"Excluded {excl} companies below the market-cap floor (₹{MIN_MARKET_CAP_CR} Cr).")

    winsor_hits = 0
    if "sector" in df.columns:
        s_low = df["sector"].fillna("").astype(str).str.lower()
        # Explanatory comment:
        # Sub-sectors are mapped to broader parent sectors to ensure small industries 
        # have a statistically significant peer group for relative metrics.
        parent_s = s_low.map(lambda x: next((v for k, v in PARENT_SECTOR_MAP.items() if k in x), x))

    for c in WINSOR_FIELDS:
        if c in df.columns and df[c].notna().sum() >= 10:
            overall_lo, overall_hi = df[c].quantile(WINSOR_PCTL), df[c].quantile(1 - WINSOR_PCTL)
            if "sector" in df.columns:
                c_sec = df.groupby(s_low)[c].transform("count")
                c_par = df.groupby(parent_s)[c].transform("count")
                lo_sec = df.groupby(s_low)[c].transform(lambda x: x.quantile(WINSOR_PCTL))
                hi_sec = df.groupby(s_low)[c].transform(lambda x: x.quantile(1-WINSOR_PCTL))
                lo_par = df.groupby(parent_s)[c].transform(lambda x: x.quantile(WINSOR_PCTL))
                hi_par = df.groupby(parent_s)[c].transform(lambda x: x.quantile(1-WINSOR_PCTL))

                lo = np.where(c_sec >= MIN_SECTOR_GROUP_SIZE, lo_sec, np.where(c_par >= MIN_SECTOR_GROUP_SIZE, lo_par, overall_lo))
                hi = np.where(c_sec >= MIN_SECTOR_GROUP_SIZE, hi_sec, np.where(c_par >= MIN_SECTOR_GROUP_SIZE, hi_par, overall_hi))
            else:
                lo, hi = overall_lo, overall_hi

            lo_s = pd.Series(lo, index=df.index).fillna(overall_lo)
            hi_s = pd.Series(hi, index=df.index).fillna(overall_hi)

            n_clip = int(((df[c] < lo_s) | (df[c] > hi_s)).sum())
            df[c] = df[c].clip(lo_s, hi_s)
            winsor_hits += n_clip

    if winsor_hits:
        log.append(f"Winsorized {winsor_hits} extreme outlier value(s) across all metrics (clipped to the 1st/99th percentile) "
                    f"so single bad data points can't distort sector comparisons.")

    log.append(f"Final universe: {len(df)} companies ready to score.")
    return df, log, colmap



# --------------------------------------------------------------------
# Sector-relative stats. Convention used everywhere below: sector_zscore()
# ALWAYS returns a "goodness" z — positive means good for the company,
# regardless of whether the underlying metric is naturally higher-is-better
# or lower-is-better. Risk-style scores simply negate a goodness z.
# --------------------------------------------------------------------

def sector_stat(df, col, stat="median"):
    overall = getattr(df[col], stat)()
    if "sector" not in df.columns:
        return pd.Series(overall, index=df.index)

    s_low = df["sector"].fillna("").astype(str).str.lower()
    parent_s = s_low.map(lambda x: next((v for k, v in PARENT_SECTOR_MAP.items() if k in x), x))
    
    counts = df.groupby("sector")[col].transform("count")
    grp = df.groupby("sector")[col].transform(stat)
    
    p_counts = df.groupby(parent_s)[col].transform("count")
    p_grp = df.groupby(parent_s)[col].transform(stat)
    
    grp = np.where(counts >= MIN_SECTOR_GROUP_SIZE, grp,
                   np.where(p_counts >= MIN_SECTOR_GROUP_SIZE, p_grp, overall))
    return pd.Series(grp, index=df.index).fillna(overall)


def sector_zscore(df, col, higher_is_better=True):
    if col not in df.columns:
        return pd.Series(0.0, index=df.index)
    mean = sector_stat(df, col, "mean")
    std = sector_stat(df, col, "std")
    overall_std = df[col].std()
    std = std.where((std > 0) & std.notna(), overall_std if overall_std and overall_std > 0 else 1)
    z = (df[col] - mean) / std
    if not higher_is_better:
        z = -z
    return z.clip(-3, 3).fillna(0)


def is_financial_sector(df):
    if "sector" not in df.columns:
        return pd.Series(False, index=df.index)
    s = df["sector"].fillna("").astype(str).str.lower()
    return s.apply(lambda x: any(k in x for k in FINANCIAL_SECTOR_KEYWORDS))


def to100(z):
    """Map a -3..+3 goodness z-score onto a 0-100 score, same convention
    used across every pillar/composite so scores are directly comparable."""
    return (50 + z * 16.67).clip(0, 100)


def mean_avail(parts):
    parts = [p for p in parts if p is not None]
    if not parts:
        return None
    # Safely average across columns, ignoring NaNs to prevent entire pillar crashes
    return pd.concat(parts, axis=1).mean(axis=1)


def restandardize(s, index):
    """
    Averaging several already-clipped z-scores shrinks variance. Re-centering 
    each pillar to std=1 across THIS uploaded universe restores real spread before 
    it's mapped to a 0-100 score, so Strong Buy/Strong Sell bands stay meaningful.
    
    Curated universes (e.g., Nifty 50, elite watchlists) naturally have a compressed 
    distribution (tighter IQR and standard deviation) because weak businesses are 
    already filtered out. We skip restandardization for these to prevent artificially 
    forcing elite companies into 'Sell' bands. Broad sectors will continue to normalize.
    """
    s = pd.Series(s, index=index).astype(float)
    std = s.std()
    
    if pd.isna(std) or std < 1e-9:
        return s.clip(-3, 3)
        
    iqr = s.quantile(0.75) - s.quantile(0.25)
    
    # Heuristic: Universe is small/medium AND score dispersion is unusually narrow.
    is_curated = (len(s) <= 250) and (iqr < 0.85 or std < 0.5)
    
    if is_curated:
        return s.clip(-3, 3)
    
    return ((s - s.mean()) / std).clip(-3, 3)


