def compute_pillars(df):
    is_fin = is_financial_sector(df)

    # ---- Quality: profitability (ROE/ROCE, correlated -> one sub-score)
    #      blended with margin quality (EBITDA margin / NPM) so no single
    #      correlated pair dominates the pillar.
    profitability_parts = []
    if "roe" in df.columns:
        profitability_parts.append(sector_zscore(df, "roe", True))
    if "roce" in df.columns:
        profitability_parts.append(sector_zscore(df, "roce", True).where(~is_fin, np.nan))
    profitability = mean_avail(profitability_parts)

    margin = mean_avail([sector_zscore(df, "ebitda_margin", True) if "ebitda_margin" in df.columns else None,
                          sector_zscore(df, "npm", True) if "npm" in df.columns else None])
    quality_z = pd.Series(mean_avail([profitability, margin]) if (profitability is not None or margin is not None) else 0.0, index=df.index)

    # ---- Growth: historical CAGR blended with forward-looking estimates,
    #      forward weighted higher since it's more decision-relevant.
    hist = mean_avail([sector_zscore(df, "revenue_growth_5y", True) if "revenue_growth_5y" in df.columns else None,
                        sector_zscore(df, "eps_growth_5y", True) if "eps_growth_5y" in df.columns else None])
                        
    fwd_rev_raw = df["revenue_growth_fwd"] if "revenue_growth_fwd" in df.columns else pd.Series(np.nan, index=df.index)
    fwd_eps_raw = df["eps_growth_fwd"] if "eps_growth_fwd" in df.columns else pd.Series(np.nan, index=df.index)
    
    fwd_rev = sector_zscore(df, "revenue_growth_fwd", True) if "revenue_growth_fwd" in df.columns else None
    fwd_eps = sector_zscore(df, "eps_growth_fwd", True) if "eps_growth_fwd" in df.columns else None
    fwd = mean_avail([fwd_rev, fwd_eps])

    if hist is not None and fwd is not None:
        fwd = pd.Series(fwd, index=df.index)
        has_parent_fwd = pd.Series(True, index=df.index)
        
        if "sector" in df.columns:
            s_low = df["sector"].fillna("").astype(str).str.lower()
            parent_s = s_low.map(lambda x: next((v for k, v in PARENT_SECTOR_MAP.items() if k in x), x))
            fwd_valid = fwd_rev_raw.notna() | fwd_eps_raw.notna()
            fwd_counts = fwd_valid.groupby(parent_s).transform("sum")
            has_parent_fwd = fwd_counts >= MIN_SECTOR_GROUP_SIZE

        # Explanatory comment:
        # Forward estimates use sector/parent medians (naturally Z=0) for missing values. 
        # If the entire parent sector lacks sufficient forward data, we fall back to historical growth.
        is_missing_fwd = fwd_rev_raw.isna() & fwd_eps_raw.isna()
        fwd_filled = np.where(is_missing_fwd & ~has_parent_fwd, hist, fwd)
        
        growth_z = 0.4 * hist + 0.6 * fwd_filled
    else:
        growth_z = hist if hist is not None else (fwd if fwd is not None else 0.0)
    
    growth_z = pd.Series(growth_z, index=df.index)

    # ---- Financial Safety: liquidity + debt serviceability + leverage,
    #      combined into ONE score rather than letting correlated ratios
    #      (current ratio doubling up with, say, quick ratio) each pull weight.
    safety_parts = []
    if "current_ratio" in df.columns:
        cr = sector_zscore(df, "current_ratio", True)
        safety_parts.append(cr.where(~is_fin, np.nan))
    if "cash_conversion_cycle" in df.columns:
        safety_parts.append(sector_zscore(df, "cash_conversion_cycle", False))
    if "interest_coverage" in df.columns:
        ic = sector_zscore(df, "interest_coverage", True)
        safety_parts.append(ic.where(~is_fin, np.nan))
    if "debt_to_ebitda" in df.columns:
        de = sector_zscore(df, "debt_to_ebitda", False)
        safety_parts.append(de.where(~is_fin, np.nan))  # leverage is structural for financials
    safety_z = pd.Series(mean_avail(safety_parts) if safety_parts else 0.0, index=df.index)

    # ---- Cash Flow: margin quality + earnings quality (does cash back up
    #      reported profit?), penalised directly when OCF/FCF go negative.
    cf_parts = []
    if "cash_flow_margin" in df.columns:
        cf_parts.append(sector_zscore(df, "cash_flow_margin", True))
    if "operating_cash_flow" in df.columns and "net_income" in df.columns:
        denom = df["net_income"]
        if "total_revenue" in df.columns:
            denom = np.where(df["net_income"] <= 0, df["total_revenue"], df["net_income"])
        
        # Guard against zero-division without throwing Pandas warnings
        ocf_to_ni = np.where(denom == 0, np.nan, df["operating_cash_flow"] / denom)
        df["_ocf_to_ni"] = pd.Series(ocf_to_ni, index=df.index).clip(-2, 4)
        cf_parts.append(sector_zscore(df, "_ocf_to_ni", True))
        
    if "free_cash_flow" in df.columns and "total_revenue" in df.columns:
        fcf_m = np.where(df["total_revenue"] == 0, np.nan, (df["free_cash_flow"] / df["total_revenue"]) * 100)
        df["_fcf_margin"] = pd.Series(fcf_m, index=df.index)
        cf_parts.append(sector_zscore(df, "_fcf_margin", True))
        
    cashflow_z = pd.Series(mean_avail(cf_parts) if cf_parts else 0.0, index=df.index)
    if "operating_cash_flow" in df.columns:
        cashflow_z = cashflow_z.where(df["operating_cash_flow"].isna() | (df["operating_cash_flow"] >= 0),
                                       cashflow_z - 1.0)  # extra penalty for cash-burning operations
    cashflow_z = cashflow_z.clip(-3, 3)

    # ---- Ownership: promoter conviction (level + 6M trend) blended with
    #      institutional conviction (DII+FII levels + 6M trend).
    promoter_parts = []
    if "promoter_holding" in df.columns:
        ph = df["promoter_holding"].fillna(50)
        insti = 0
        if "dii_holding" in df.columns: insti += df["dii_holding"].fillna(0)
        if "fii_holding" in df.columns: insti += df["fii_holding"].fillna(0)
        
        # Widely-held mitigation: if institutional holding is substantial (>40%), do not penalize low promoter holding
        low_ph_z = np.where(insti > 40, 0.0, (ph - 50) / 20)
        ph_z = np.where(ph < 50, low_ph_z, np.where(ph > 75, (75 - ph) / 10, 1.0))
        promoter_parts.append(pd.Series(ph_z, index=df.index).clip(-2, 2))
        
    if "promoter_change_6m" in df.columns:
        promoter_parts.append(sector_zscore(df, "promoter_change_6m", True))
    inst_parts = [sector_zscore(df, c, True) for c in ("dii_holding", "fii_holding", "dii_change_6m", "fii_change_6m") if c in df.columns]
    promoter_z = mean_avail(promoter_parts)
    inst_z = mean_avail(inst_parts)
    ownership_z = pd.Series(mean_avail([promoter_z, inst_z]) if (promoter_z is not None or inst_z is not None) else 0.0, index=df.index)

    # ---- Momentum: small weight by design (price action, not fundamentals).
    mom_parts = []
    if "return_6m" in df.columns:
        mom_parts.append(sector_zscore(df, "return_6m", True))
    elif "return_1m" in df.columns:
        mom_parts.append(sector_zscore(df, "return_1m", True))
    if "pct_from_52w_high" in df.columns:
        mom_parts.append(sector_zscore(df, "pct_from_52w_high", False))
    momentum_z = pd.Series(mean_avail(mom_parts) if mom_parts else 0.0, index=df.index)

    # ---- Valuation: cheaper (relative to sector) is better across every
    #      available multiple.
    val_parts = [sector_zscore(df, c, False) for c in ("pe", "pb", "ev_ebitda") if c in df.columns]
    valuation_z = pd.Series(mean_avail(val_parts) if val_parts else 0.0, index=df.index)
    
    # Explanatory comment:
    # Valuation is quality-gated. A stock gets full credit for being extremely cheap 
    # only if its Quality, Cash Flow, or Safety scores clear the minimum threshold (Z >= 0). 
    # Otherwise, deep value is penalized as a potential value trap.
    val_dampener = np.where((valuation_z > 0) & (quality_z < 0) & (cashflow_z < 0) & (safety_z < 0), 0.5, 1.0)
    valuation_z = valuation_z * val_dampener

    raw_pillars = {
        "quality": quality_z.fillna(0.0), 
        "growth": growth_z.fillna(0.0), 
        "valuation": valuation_z.fillna(0.0),
        "safety": safety_z.fillna(0.0), 
        "cashflow": cashflow_z.fillna(0.0), 
        "ownership": ownership_z.fillna(0.0),
        "momentum": momentum_z.fillna(0.0),
    }
    return {k: restandardize(v, df.index) for k, v in raw_pillars.items()}


def compute_confidence(df, pillar_z):
    """0-100. Independent of the Investment Score — measures how much we
    should TRUST that score, based on data completeness, not quality of
    the business."""
    CORE_METRICS = ["market_cap", "cmp", "pe", "roe", "net_income", "total_revenue"]
    scoring_fields = [c for c in CORE_METRICS if c in df.columns]
    if scoring_fields:
        coverage = df[scoring_fields].notna().sum(axis=1) / len(scoring_fields)
    else:
        coverage = pd.Series(0.0, index=df.index)

    pillars_available = pd.Series(0, index=df.index)
    for z in pillar_z.values():
        pillars_available = pillars_available + (z.abs() > 1e-9).astype(int)
    pillars_available = (pillars_available / len(pillar_z)).clip(0, 1)

    conf = 100 * (0.8 * coverage + 0.2 * pillars_available)
    return to_safe_int(conf, 0)


def compute_risk(df, is_fin):
    """0 (low risk) - 100 (high risk). A downside-risk lens, distinct from
    the Investment Score: measures how badly this could go wrong, not how
    good the opportunity looks."""
    risk_parts = []
    weights = []
    if "debt_to_ebitda" in df.columns:
        risk_parts.append(-sector_zscore(df, "debt_to_ebitda", False).where(~is_fin, 0))
        weights.append(0.30)
    if "interest_coverage" in df.columns:
        risk_parts.append((-sector_zscore(df, "interest_coverage", True)).where(~is_fin, 0))
        weights.append(0.25)
    if "current_ratio" in df.columns:
        risk_parts.append(-sector_zscore(df, "current_ratio", True).where(~is_fin, 0))
        weights.append(0.15)
    if "_fcf_margin" in df.columns or "cash_flow_margin" in df.columns:
        cf_col = "_fcf_margin" if "_fcf_margin" in df.columns else "cash_flow_margin"
        risk_parts.append(-sector_zscore(df, cf_col, True))
        weights.append(0.15)
    if "promoter_change_6m" in df.columns:
        risk_parts.append(-sector_zscore(df, "promoter_change_6m", True))
        weights.append(0.10)
    if "beta" in df.columns:
        risk_parts.append(-sector_zscore(df, "beta", False))
        weights.append(0.05)

    if not risk_parts:
        risk_z = pd.Series(0.0, index=df.index)
    else:
        w = np.array(weights) / sum(weights)
        risk_z = sum(p * wi for p, wi in zip(risk_parts, w))
        risk_z = restandardize(risk_z, df.index)

    risk_score = to100(risk_z)
    return to_safe_int(risk_score, 50)


def band_label(score, bands):
    for cutoff, label in bands:
        if score <= cutoff:
            return label
    return bands[-1][1]


def compute_red_flags(df, is_fin):
    is_retail = pd.Series(False, index=df.index)
    if "sector" in df.columns:
        s_low = df["sector"].fillna("").astype(str).str.lower()
        is_retail = s_low.apply(lambda x: any(k in x for k in ["retail", "fmcg", "consumer staple", "textile"]))
        
    flags = pd.DataFrame(index=df.index)
    t = RED_FLAG_THRESHOLDS
    if "current_ratio" in df.columns:
        f = df["current_ratio"] < t["current_ratio_min"]
        flags["Weak liquidity (current ratio < 1)"] = f.where(~is_fin & ~is_retail, False)
    if "interest_coverage" in df.columns:
        f = df["interest_coverage"] < t["interest_coverage_min"]
        flags["Weak interest coverage (< 2x)"] = f.where(~is_fin, False)
    if "debt_to_ebitda" in df.columns:
        f = df["debt_to_ebitda"] > t["debt_to_ebitda_max"]
        flags["High debt (Debt/EBITDA > 4x)"] = f.where(~is_fin, False)
    if "npm" in df.columns:
        flags["Structurally loss-making (5Y avg NPM < 0)"] = df["npm"] < t["npm_min"]
    if "revenue_growth_5y" in df.columns:
        flags["Weak growth (5Y revenue growth < -10%)"] = df["revenue_growth_5y"] < t["revenue_growth_min"]
    if "operating_cash_flow" in df.columns:
        flags["Negative operating cash flow"] = df["operating_cash_flow"] < 0
    if "free_cash_flow" in df.columns:
        flags["Negative free cash flow"] = df["free_cash_flow"] < 0
    if "net_income" in df.columns:
        flags["Net loss-making"] = df["net_income"] < 0
    if "book_value" in df.columns:
        flags["Negative net worth (book value < 0)"] = df["book_value"] < 0
    if "promoter_change_6m" in df.columns:
        f = df["promoter_change_6m"] <= t["promoter_selldown_max"]
        if "promoter_holding" in df.columns:
            prev_holding = df["promoter_holding"] - df["promoter_change_6m"]
            is_sebi_selldown = prev_holding >= 74.5
            f = f & ~is_sebi_selldown
        flags["Promoter selling (6M holding change)"] = f

    if flags.shape[1] == 0:
        count = pd.Series(0, index=df.index)
        names = pd.Series([[] for _ in range(len(df))], index=df.index)
        return to_safe_int(count, 0), names

    count = flags.sum(axis=1)
    names = flags.apply(lambda row: [c for c in flags.columns if row[c]], axis=1)
    return to_safe_int(count, 0), names


def compute_composite(df, pillar_z):
    z = sum(pillar_z[k] * w for k, w in PILLAR_WEIGHTS.items())
    z = restandardize(z, df.index)
    score = to100(z)
    return z, to_safe_int(score, 50)


def compute_opportunity(pillar_z, df):
    # Opportunity = "good, growing, and still cheap" -- distinct from the
    # Investment Score because it deliberately ignores Safety/Cashflow/
    # Ownership/Momentum: a stock can be a great opportunity today even if
    # its balance sheet score is merely average.
    opp_z = 0.35 * pillar_z["quality"] + 0.35 * pillar_z["growth"] + 0.30 * pillar_z["valuation"]
    opp_z = restandardize(opp_z, df.index)
    base_opp = to100(opp_z)
    safety = to100(pillar_z["safety"])
    cf = to100(pillar_z["cashflow"])
    penalty = pd.Series(np.where((safety < 40) | (cf < 40), 20, 0), index=df.index)
    return to_safe_int((base_opp - penalty).clip(0, 100), 50)


def compute_peg(df):
    if "pe" in df.columns and "eps_growth_fwd" in df.columns:
        return np.where(df["eps_growth_fwd"] > 0, df["pe"] / df["eps_growth_fwd"], np.nan)
    if "pe" in df.columns and "eps_growth_5y" in df.columns:
        return np.where(df["eps_growth_5y"] > 0, df["pe"] / df["eps_growth_5y"], np.nan)
    return np.full(len(df), np.nan)


def signal_for_row(z, quality_score, redflag_count):
    z_adj = z - (redflag_count * 0.4)
    if redflag_count >= 3:
        return "Strong Sell"
    if z_adj >= 1.00 and quality_score >= 65:
        return "Strong Buy"
    elif z_adj >= 0.30:
        return "Buy"
    elif z_adj > -0.30:
        return "Hold"
    elif z_adj > -1.00:
        return "Sell"
    return "Strong Sell"


def compute_shortlist(df, quality_score, redflag_count, signal, peg):
    ok = (quality_score >= SHORTLIST_MIN_QUALITY) & (redflag_count == 0) & signal.isin(["Buy", "Strong Buy"])
    peg_ok = pd.Series(True, index=df.index)
    has_peg = pd.notna(peg)
    peg_ok[has_peg] = peg[has_peg] < SHORTLIST_MAX_PEG
    return ok & peg_ok


def classify_styles(df, pillar_score, risk_score, sector_median_div_yield):
    styles = pd.Series([[] for _ in range(len(df))], index=df.index)
    q, g, v, s = pillar_score["quality"], pillar_score["growth"], pillar_score["valuation"], pillar_score["safety"]

    def add(mask, label):
        for i in df.index[mask.fillna(False)]:
            styles[i] = styles[i] + [label]

    add((q >= 65) & (g >= 55) & (s >= 55), "Compounder")
    add(g >= 70, "Growth")
    add((v >= 70) & (q >= 45), "Value")

    if "dividend_yield" in df.columns:
        dy_ok = (df["dividend_yield"] >= sector_median_div_yield) & (df["dividend_yield"] > 1.5) & (s >= 50)
        add(dy_ok, "Dividend")

    if "eps_growth_fwd" in df.columns and "eps_growth_5y" in df.columns:
        turn = (df["eps_growth_fwd"] > df["eps_growth_5y"] + 10) & (df["eps_growth_fwd"] > 0) & (q < 55)
        add(turn, "Turnaround")

    if "sector" in df.columns:
        s_low = df["sector"].fillna("").astype(str).str.lower()
        is_cyc = s_low.apply(lambda x: any(k in x for k in ["auto", "metal", "mining", "real estate", "capital goods", "chemical", "hotel", "airline", "infrastructure", "cement"]))
        is_def = s_low.apply(lambda x: any(k in x for k in ["fmcg", "utilit", "health", "consumer staple", "pharma"]))
        add(is_cyc, "Cyclical")
        add(is_def, "Defensive")

    add(risk_score >= 65, "High Risk")

    styles = styles.apply(lambda lst: lst if lst else ["Unclassified"])
    return styles



