def fmt(v, unit):
    if pd.isna(v):
        return "n/a"
    if unit == "x":
        return f"{v:.1f}x"
    if unit == "pp":
        return f"{v:+.1f}pp"
    return f"{v:.1f}%"


def build_strengths_weaknesses(df):
    """Per-row goodness z for each explainable metric, then pick the
    strongest positives/negatives as plain-language bullets."""
    strengths, weaknesses = [], []
    per_metric_z = {}
    per_metric_med = {}
    for field, (label, unit, hib, template) in METRIC_META.items():
        if field not in df.columns:
            continue
        per_metric_z[field] = sector_zscore(df, field, hib)
        per_metric_med[field] = sector_stat(df, field, "median")

    for i in df.index:
        pos, neg = [], []
        for field, z in per_metric_z.items():
            zi = z.loc[i]
            val = df.at[i, field]
            if pd.isna(val):
                continue
            label, unit, hib, template = METRIC_META[field]
            med = per_metric_med[field].loc[i]
            cmp_word = "above" if val >= med else "below"
            sentence = template.format(val=fmt(val, unit), med=fmt(med, unit), cmp=cmp_word)
            if zi >= 0.5:
                pos.append((zi, sentence))
            elif zi <= -0.5:
                neg.append((zi, sentence))
        pos.sort(key=lambda t: -t[0])
        neg.sort(key=lambda t: t[0])
        strengths.append([s for _, s in pos[:4]])
        weaknesses.append([s for _, s in neg[:4]])
    return (pd.Series(strengths, index=df.index), pd.Series(weaknesses, index=df.index))


def build_thesis(company, signal, score, risk, opp, styles, redflags, strengths, weaknesses, top_p, bot_p):
    style_txt = " / ".join(styles)
    risk_band = "low" if risk < 35 else "moderate" if risk < 65 else "high"

    if signal in ["Strong Buy", "Buy"]:
        reason = f"driven primarily by strong {top_p}"
    elif signal in ["Strong Sell", "Sell"]:
        reason = f"weighed down by weak {bot_p}"
    else:
        reason = f"with mixed factor alignment (strongest: {top_p}, weakest: {bot_p})"

    thesis = (f"{company} carries an Investment Score of {score}/100 with a {signal} signal, "
              f"screening as a {style_txt} profile at {risk_band} downside risk, {reason}.")

    bull_pts = strengths[:2] if strengths else ["No standout strengths clear the sector-relative bar on the metrics available."]
    bear_pts = weaknesses[:2] if weaknesses else ["No major sector-relative weaknesses detected on the metrics available."]

    bull = "Bull case: " + "; ".join(bull_pts) + "."
    bear = "Bear case: " + "; ".join(bear_pts) + ("; flagged for " + ", ".join(redflags) + "." if redflags else ".")

    risk_summary = (f"Risk Score of {risk}/100 places this in the {risk_band}-risk band"
                     + (f", driven in part by: {redflags[0]}." if redflags else "."))

    if opp >= 65:
        opportunity_summary = f"Opportunity Score of {opp}/100 suggests the current quality/growth combination looks attractively priced today."
    elif opp <= 35:
        opportunity_summary = f"Opportunity Score of {opp}/100 suggests the stock looks expensive relative to its quality and growth profile today."
    else:
        opportunity_summary = f"Opportunity Score of {opp}/100 is middling — fairly priced for what it offers, not a standout either way."

    if "High Risk" in styles or risk >= 65:
        suitability = "Better suited to investors with a higher risk tolerance and a longer holding horizon to ride out volatility."
    elif "Defensive" in styles or "Dividend" in styles:
        suitability = "Better suited to conservative, income- or stability-oriented investors."
    elif "Growth" in styles or "Compounder" in styles:
        suitability = "Better suited to growth-oriented investors comfortable holding through valuation swings."
    else:
        suitability = "Fits a core/balanced allocation rather than a high-conviction thematic bet."

    return {
        "thesis": thesis, "bull": bull, "bear": bear,
        "risk_summary": risk_summary, "opportunity_summary": opportunity_summary,
        "suitability": suitability,
    }


def sector_summary_table(df, inv_score, risk, pillar_score):
    if "sector" not in df.columns:
        return []
    tmp = df.copy()
    tmp["_score"] = inv_score
    tmp["_risk"] = risk
    for k, v in pillar_score.items():
        tmp[f"_p_{k}"] = v
    rows = []
    for sector, g in tmp.groupby("sector"):
        if len(g) == 0 or pd.isna(sector) or str(sector).strip() == "":
            continue
        top_idx = g["_score"].idxmax()
        rows.append({
            "sector": sector,
            "n": int(len(g)),
            "avg_score": round(float(g["_score"].mean()), 1),
            "avg_risk": round(float(g["_risk"].mean()), 1),
            "top_company": str(df.at[top_idx, "company"]),
            "top_score": int(g["_score"].max()),
            "pillars": {k: round(float(g[f"_p_{k}"].mean()), 1) for k in pillar_score},
        })
    rows.sort(key=lambda r: -r["avg_score"])
    return rows


